const (
	// NonceHTMLPlaceholder is the placeholder for nonce in HTML script tags
	NonceHTMLPlaceholder = "__CSP_NONCE_VALUE__"
	frontendLoginPath    = "/login"
	robotsNoIndexHeader  = "noindex, nofollow, noarchive"
)

//go:embed all:dist
var frontendFS embed.FS

// PublicSettingsProvider is an interface to fetch public settings
type PublicSettingsProvider interface {
	GetPublicSettingsForInjection(ctx context.Context) (any, error)
}

// FrontendServer serves the embedded frontend with settings injection
type FrontendServer struct {
	distFS      fs.FS
	fileServer  http.Handler
	baseHTML    []byte
	cache       *HTMLCache
	settings    PublicSettingsProvider
	overrideDir string // local file override directory
}

// NewFrontendServer creates a new frontend server with settings injection
func NewFrontendServer(settingsProvider PublicSettingsProvider) (*FrontendServer, error) {
	distFS, err := fs.Sub(frontendFS, "dist")
	if err != nil {
		return nil, err
	}

	// Read base HTML once
	file, err := distFS.Open("index.html")
	if err != nil {
		return nil, err
	}
	defer func() { _ = file.Close() }()

	baseHTML, err := io.ReadAll(file)
	if err != nil {
		return nil, err
	}

	cache := NewHTMLCache()
	cache.SetBaseHTML(baseHTML)

	return &FrontendServer{
		distFS:      distFS,
		fileServer:  http.FileServer(http.FS(distFS)),
		baseHTML:    baseHTML,
		cache:       cache,
		settings:    settingsProvider,
		overrideDir: filepath.Join("data", "public"),
	}, nil
}

// InvalidateCache invalidates the HTML cache (call when settings change)
func (s *FrontendServer) InvalidateCache() {
	if s != nil && s.cache != nil {
		s.cache.Invalidate()
	}
}

// Middleware returns the Gin middleware handler
func (s *FrontendServer) Middleware() gin.HandlerFunc {
	return func(c *gin.Context) {
		path := c.Request.URL.Path

		// Skip API routes
		if shouldBypassEmbeddedFrontend(path, true) {
			if isPublicSSRRoute(path) {
				servePublicSSRInShell(c, s.shellHTML)
				return
			}
			c.Next()
			return
		}
		if isHomeAliasRoute(path) {
			redirectCanonicalHome(c)
			return
		}

		cleanPath := strings.TrimPrefix(path, "/")
		if cleanPath == "" {
			cleanPath = "index.html"
		}

		// For index.html or SPA routes, serve with injected settings
		if cleanPath == "index.html" || !s.fileExists(cleanPath) {
			if shouldRedirectFrontendRouteToLogin(path) {
				redirectFrontendRouteToLogin(c)
				return
			}
			s.serveIndexHTML(c)
			return
		}

		// Try local override first
		if s.tryServeOverride(c, cleanPath) {
			return
		}

		// Serve static files normally
		s.fileServer.ServeHTTP(c.Writer, c.Request)
		c.Abort()
	}
}

func (s *FrontendServer) fileExists(path string) bool {
	file, err := s.distFS.Open(path)
	if err != nil {
		return false
	}
	_ = file.Close()
	return true
}

// tryServeOverride checks if a local override file exists and serves it.
// Files in overrideDir take precedence over embedded files.
func (s *FrontendServer) tryServeOverride(c *gin.Context, cleanPath string) bool {
	if s.overrideDir == "" {
		return false
	}
	filePath := filepath.Join(s.overrideDir, filepath.Clean("/"+cleanPath))
	info, err := os.Stat(filePath)
	if err != nil || info.IsDir() {
		return false
	}
	c.File(filePath)
	c.Abort()
	return true
}

func (s *FrontendServer) serveIndexHTML(c *gin.Context) {
	// Get nonce from context (generated by SecurityHeaders middleware)
	nonce := middleware.GetNonceFromContext(c)
	c.Header("X-Robots-Tag", robotsHeaderForFrontendPath(c.Request.URL.Path))
	c.Header("Cache-Control", "no-cache")

	// 带 CSP nonce 的页面每次响应体都不同（nonce 每请求新生成），不能用 ETag/304：
	// 浏览器收到 304 会沿用旧正文里的旧 nonce，却套上新响应头里的新 CSP，
	// 内联的 window.__APP_CONFIG__ 脚本被拦截（实测 /login 第二次访问即报 CSP 违规）。
	useETag := nonce == ""

	// Check cache first
	cached := s.cache.Get()
	if cached != nil {
		// Check If-None-Match for 304 response
		if useETag && c.GetHeader("If-None-Match") == cached.ETag {
			c.Status(http.StatusNotModified)
			c.Abort()
			return
		}

		// Replace nonce placeholder with actual nonce before serving
		content := replaceNoncePlaceholder(cached.Content, nonce)

		if useETag {
			c.Header("ETag", cached.ETag)
		}
		c.Data(http.StatusOK, "text/html; charset=utf-8", content)
		c.Abort()
		return
	}

	// Cache miss - fetch settings and render
	ctx, cancel := context.WithTimeout(c.Request.Context(), 2*time.Second)
	defer cancel()

	settings, err := s.settings.GetPublicSettingsForInjection(ctx)
	if err != nil {
		// Fallback: serve without injection
		c.Header("X-Robots-Tag", robotsHeaderForFrontendPath(c.Request.URL.Path))
		c.Data(http.StatusOK, "text/html; charset=utf-8", s.baseHTML)
		c.Abort()
		return
	}

	settingsJSON, err := json.Marshal(settings)
	if err != nil {
		// Fallback: serve without injection
		c.Header("X-Robots-Tag", robotsHeaderForFrontendPath(c.Request.URL.Path))
		c.Data(http.StatusOK, "text/html; charset=utf-8", s.baseHTML)
		c.Abort()
		return
	}

	rendered := s.injectSettings(settingsJSON)
	s.cache.Set(rendered, settingsJSON)

	// Replace nonce placeholder with actual nonce before serving
	content := replaceNoncePlaceholder(rendered, nonce)

	cached = s.cache.Get()
	if cached != nil && useETag {
		c.Header("ETag", cached.ETag)
	}
	c.Data(http.StatusOK, "text/html; charset=utf-8", content)
	c.Abort()
}

// shellHTML returns the SPA index.html with settings and the request nonce
// injected, for wrapping public SSR pages (see public_ssr_shell.go).
func (s *FrontendServer) shellHTML(c *gin.Context) []byte {
	nonce := middleware.GetNonceFromContext(c)
	if cached := s.cache.Get(); cached != nil {
		return replaceNoncePlaceholder(cached.Content, nonce)
	}
	ctx, cancel := context.WithTimeout(c.Request.Context(), 2*time.Second)
	defer cancel()
	if s.settings != nil {
		if settings, err := s.settings.GetPublicSettingsForInjection(ctx); err == nil {
			if settingsJSON, err := json.Marshal(settings); err == nil {
				rendered := s.injectSettings(settingsJSON)
				s.cache.Set(rendered, settingsJSON)
				return replaceNoncePlaceholder(rendered, nonce)
			}
		}
	}
	return replaceNoncePlaceholder(s.baseHTML, nonce)
}

func (s *FrontendServer) injectSettings(settingsJSON []byte) []byte {
	// Create the script tag to inject with nonce placeholder
	// The placeholder will be replaced with actual nonce at request time
	script := []byte(`<script nonce="` + NonceHTMLPlaceholder + `">window.__APP_CONFIG__=` + string(settingsJSON) + `;</script>`)

	// Inject before </head>
	headClose := []byte("</head>")
	result := bytes.Replace(s.baseHTML, headClose, append(script, headClose...), 1)

	// Replace <title> with custom site name so the browser tab shows it immediately
	result = injectSiteTitle(result, settingsJSON)

	return result
}

// injectSiteTitle replaces the static <title> in HTML with the configured site name.
// This ensures the browser tab shows the correct title before JS executes.
func injectSiteTitle(html, settingsJSON []byte) []byte {
	var cfg struct {
		SiteName string `json:"site_name"`
	}
	if err := json.Unmarshal(settingsJSON, &cfg); err != nil || cfg.SiteName == "" {
		return html
	}

	// Find and replace the existing <title>...</title>
	titleStart := bytes.Index(html, []byte("<title>"))
	titleEnd := bytes.Index(html, []byte("</title>"))
	if titleStart == -1 || titleEnd == -1 || titleEnd <= titleStart {
		return html
	}

	newTitle := []byte("<title>" + cfg.SiteName + " - AI API Gateway</title>")
	result := make([]byte, 0, len(html)-titleEnd-len("</title>")+titleStart+len(newTitle))
	result = append(result, html[:titleStart]...)
	result = append(result, newTitle...)
	result = append(result, html[titleEnd+len("</title>"):]...)
	return result
}

// replaceNoncePlaceholder replaces the nonce placeholder with actual nonce value
func replaceNoncePlaceholder(html []byte, nonce string) []byte {
	return bytes.ReplaceAll(html, []byte(NonceHTMLPlaceholder), []byte(nonce))
}

// ServeEmbeddedFrontend returns a middleware for serving embedded frontend
// This is the legacy function for backward compatibility when no settings provider is available
func ServeEmbeddedFrontend() gin.HandlerFunc {
	return serveEmbeddedFrontend(true)
}

// ServeEmbeddedFrontendWithoutPublicSSR serves the setup wizard's SPA without
// bypassing public paths that are only registered by the main server.
func ServeEmbeddedFrontendWithoutPublicSSR() gin.HandlerFunc {
	return serveEmbeddedFrontend(false)
}

func serveEmbeddedFrontend(publicSSR bool) gin.HandlerFunc {
	distFS, err := fs.Sub(frontendFS, "dist")
	if err != nil {
		panic("failed to get dist subdirectory: " + err.Error())
	}
	fileServer := http.FileServer(http.FS(distFS))
	overrideDir := filepath.Join("data", "public")

	return func(c *gin.Context) {
		path := c.Request.URL.Path

		if shouldBypassEmbeddedFrontend(path, publicSSR) {
			if publicSSR && isPublicSSRRoute(path) {
				servePublicSSRInShell(c, func(c *gin.Context) []byte {
					shell, err := fs.ReadFile(distFS, "index.html")
					if err != nil {
						return nil
					}
					return replaceNoncePlaceholder(shell, middleware.GetNonceFromContext(c))
				})
				return
			}
			c.Next()
			return
		}
		if isHomeAliasRoute(path) {
			redirectCanonicalHome(c)
			return
		}

		cleanPath := strings.TrimPrefix(path, "/")
		if cleanPath == "" {
			cleanPath = "index.html"
		}

		if cleanPath == "index.html" {
			if shouldRedirectFrontendRouteToLogin(path) {
				redirectFrontendRouteToLogin(c)
				return
			}
			serveIndexHTML(c, distFS)
			return
		}

		if file, err := distFS.Open(cleanPath); err == nil {
			_ = file.Close()
			// Try local override first
			if tryServeOverrideFile(c, overrideDir, cleanPath) {
				return
			}
			fileServer.ServeHTTP(c.Writer, c.Request)
			c.Abort()
			return
		}

		if shouldRedirectFrontendRouteToLogin(path) {
			redirectFrontendRouteToLogin(c)
			return
		}

		serveIndexHTML(c, distFS)
	}
}

// tryServeOverrideFile is a standalone version of tryServeOverride for legacy usage.
func tryServeOverrideFile(c *gin.Context, overrideDir, cleanPath string) bool {
	if overrideDir == "" {
		return false
	}
	filePath := filepath.Join(overrideDir, filepath.Clean("/"+cleanPath))
	info, err := os.Stat(filePath)
	if err != nil || info.IsDir() {
		return false
	}
	c.File(filePath)
	c.Abort()
	return true
}

func shouldBypassEmbeddedFrontend(path string, publicSSR bool) bool {
	trimmed := strings.TrimSpace(path)
	if publicSSR && isPublicSSRRoute(trimmed) {
		return true
	}
	return strings.HasPrefix(trimmed, "/api/") ||
		strings.HasPrefix(trimmed, "/v1/") ||
		strings.HasPrefix(trimmed, "/v1beta/") ||
		strings.HasPrefix(trimmed, "/backend-api/") ||
		strings.HasPrefix(trimmed, "/antigravity/") ||
		strings.HasPrefix(trimmed, "/setup/") ||
		trimmed == "/health" ||
		trimmed == "/responses" ||
		strings.HasPrefix(trimmed, "/responses/") ||
		strings.HasPrefix(trimmed, "/images/") ||
		// 内容中心上传的图片由 r.Static("/media/content", ...) 托管，文件不在内嵌 dist 里。
		// 不放行会被下面的 SPA fallback 抢走：fileExists=false → 重定向 /login，
		// 于是后台封面预览和公开页封面全部变成「挂掉的图」（实测 302 → /login）。
		strings.HasPrefix(trimmed, "/media/")
}

// isPublicSSRRoute lets the registered Go handlers render crawlable pages
// before the SPA fallback can serve index.html or redirect to login.
func isPublicSSRRoute(path string) bool {
	normalized := normalizeFrontendRoutePath(path)
	if normalized == "/" || normalized == "/news" || normalized == "/articles" || normalized == "/docs" || normalized == "/robots.txt" || normalized == "/sitemap.xml" {
		return true
	}
	if strings.HasPrefix(normalized, "/news/") ||
		strings.HasPrefix(normalized, "/articles/") ||
		strings.HasPrefix(normalized, "/docs/") {
		return true
	}
	// Language-prefixed pages (`/zh/`, `/en/news`, `/ru/articles`, ...) must
	// reach the Gin SSR handlers instead of the SPA/login branch (R12-06).
	return isPublicLocalePrefixedRoute(normalized)
}

// isPublicLocalePrefixedRoute matches `/<lang>` and `/<lang>/{news,articles,docs}`.
// The first segment only has to *look* like a language tag: unsupported tags
// (e.g. `/xx/news`) are deliberately admitted so the router can answer 404
// instead of redirecting the crawler to login (R12-05).
func isPublicLocalePrefixedRoute(normalized string) bool {
	segments := strings.Split(strings.TrimPrefix(normalized, "/"), "/")
	if len(segments) == 0 || !looksLikeLocaleTag(segments[0]) {
		return false
	}
	if len(segments) == 1 {
		return true
	}
	switch segments[1] {
	case "news", "articles", "docs":
		return true
	default:
		return false
	}
}

// looksLikeLocaleTag accepts `xx` and `xx-YY`/`xx_YY` shapes (zh, en, zh-CN,
// en_US, ...) without validating the language against the supported set.
func looksLikeLocaleTag(segment string) bool {
	parts := strings.FieldsFunc(segment, func(r rune) bool { return r == '-' || r == '_' })
	if len(parts) != 1 && len(parts) != 2 {
		return false
	}
	for _, part := range parts {
		if len(part) != 2 {
			return false
		}
		for _, r := range part {
			if !(r >= 'a' && r <= 'z') && !(r >= 'A' && r <= 'Z') {
				return false
			}
		}
	}
	return true
}

func shouldRedirectFrontendRouteToLogin(path string) bool {
	return !isPublicFrontendRoute(path)
}

func isHomeAliasRoute(path string) bool {
	return normalizeFrontendRoutePath(path) == "/home"
}

func isPublicFrontendRoute(path string) bool {
	normalized := normalizeFrontendRoutePath(path)
	if normalized == "" {
		normalized = "/"
	}

	switch normalized {
	case "/", "/home", "/news", "/articles", "/docs":
		return true
	case frontendLoginPath,
		"/register",
		"/setup",
		"/email-verify",
		"/auth/callback",
		"/auth/oauth/callback",
		"/auth/linuxdo/callback",
		"/auth/wechat/callback",
		"/auth/wechat/payment/callback",
		"/auth/oidc/callback",
		"/forgot-password",
		"/reset-password",
		"/key-usage",
		"/payment/result",
		"/payment/stripe",
		"/payment/airwallex",
		"/payment/stripe-popup":
		return true
	}

	return normalized == "/legal" || strings.HasPrefix(normalized, "/legal/") ||
		strings.HasPrefix(normalized, "/news/") ||
		strings.HasPrefix(normalized, "/articles/") ||
		strings.HasPrefix(normalized, "/docs/")
}

func isIndexableFrontendRoute(path string) bool {
	normalized := normalizeFrontendRoutePath(path)
	return normalized == "/" || normalized == "/home" ||
		normalized == "/news" || normalized == "/articles" || normalized == "/docs"
}

func robotsHeaderForFrontendPath(path string) string {
	if isIndexableFrontendRoute(path) {
		return "index,follow"
	}
	return robotsNoIndexHeader
}

func normalizeFrontendRoutePath(path string) string {
	trimmed := strings.TrimSpace(path)
	if trimmed == "" {
		return "/"
	}
	if !strings.HasPrefix(trimmed, "/") {
		trimmed = "/" + trimmed
	}
	if trimmed != "/" {
		trimmed = strings.TrimRight(trimmed, "/")
	}
	return trimmed
}

func redirectFrontendRouteToLogin(c *gin.Context) {
	c.Header("X-Robots-Tag", robotsHeaderForFrontendPath(c.Request.URL.Path))
	c.Redirect(http.StatusFound, frontendLoginPath)
	c.Abort()
}

func redirectCanonicalHome(c *gin.Context) {
	target := "/"
	if c.Request.URL.RawQuery != "" {
		target += "?" + c.Request.URL.RawQuery
	}
	c.Header("X-Robots-Tag", "index,follow")
	c.Redirect(http.StatusMovedPermanently, target)
	c.Abort()
}

func serveIndexHTML(c *gin.Context, fsys fs.FS) {
	file, err := fsys.Open("index.html")
	if err != nil {
		c.String(http.StatusNotFound, "Frontend not found")
		c.Abort()
		return
	}
	defer func() { _ = file.Close() }()

	content, err := io.ReadAll(file)
	if err != nil {
		c.String(http.StatusInternalServerError, "Failed to read index.html")
		c.Abort()
		return
	}

	c.Header("X-Robots-Tag", robotsHeaderForFrontendPath(c.Request.URL.Path))
	c.Data(http.StatusOK, "text/html; charset=utf-8", content)
	c.Abort()
}

func HasEmbeddedFrontend() bool {
	_, err := frontendFS.ReadFile("dist/index.html")
	return err == nil
}
